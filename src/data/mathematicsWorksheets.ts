export function getActiveWorksheetsByTopicSlug(topicSlug: string): Worksheet[] {
  return mathematicsWorksheets.filter(
    (worksheet) => worksheet.topicSlug === topicSlug && worksheet.isActive,
  );
}

export function getMathematicsWorksheetBySlug(slug: string | undefined) {
  return mathematicsWorksheets.find((worksheet) => worksheet.slug === slug);
}

export function getRelatedWorksheets(
  topicSlug: string,
  excludedWorksheetSlug: string,
  limit = 4,
): Worksheet[] {
  return mathematicsWorksheets
    .filter(
      (worksheet) =>
        worksheet.topicSlug === topicSlug &&
        worksheet.slug !== excludedWorksheetSlug &&
        worksheet.isActive,
    )
    .slice(0, limit);
}
